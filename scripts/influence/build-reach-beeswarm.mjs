#!/usr/bin/env node
/**
 * Preview view A for /reach (docs/reach/VIZ-ALT-REPORT.md): the Ripple keywords as one
 * beeswarm row per theme, x = mean reach distance. Layout only; every number is read
 * from the Ripple builder's output, so run build-ripple.mjs first.
 *
 * Input:   src/data/ripple.json
 * Output:  src/data/reach-beeswarm.json
 * Usage:   node scripts/influence/build-reach-beeswarm.mjs [--dry-run]
 */

import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { ROOT } from "./lib/openalex.mjs";
import { layoutBeeswarm } from "./lib/reach-alt-layout.mjs";

const DRY_RUN = process.argv.includes("--dry-run");
const RIPPLE_PATH = join(ROOT, "src", "data", "ripple.json");
const OUT_PATH = join(ROOT, "src", "data", "reach-beeswarm.json");

/** wide: ≥ 720 px (a ~720 px column, close to 1:1); narrow: phones (~340 px). */
const SPECS = {
  wide: { width: 720, x0: 26, x1: 694, rMax: 18, rMin: 4, gap: 2, labelSize: 12, pad: 6, laneGap: 3, badge: 8 },
  narrow: { width: 340, x0: 16, x1: 324, rMax: 13, rMin: 4, gap: 2, labelSize: 11, pad: 6, laneGap: 3, badge: 7 },
};

const round = (v, dp = 1) => Math.round(v * 10 ** dp) / 10 ** dp;
const radius = (v, max, rMax, rMin) => Math.max(rMin, rMax * Math.sqrt(v / max));

const ripple = JSON.parse(readFileSync(RIPPLE_PATH, "utf8"));
const out = {
  $comment:
    "Generated by scripts/influence/build-reach-beeswarm.mjs from src/data/ripple.json (preview view A). Layout only: counts, distances and themes are the Ripple's. Do not edit by hand.",
};

for (const lens of ["all", "lead"]) {
  const view = ripple[lens];
  const { maxWorks, maxPerYear } = view.meta.scale;
  const maxD = view.layout.circle.maxD;
  const calloutRank = new Map(view.callouts.map((c, i) => [c.keyword, i + 1]));
  out[lens] = { meta: { asOf: view.meta.asOf, lens, maxD } };
  for (const [name, spec] of Object.entries(SPECS)) {
    const keywords = view.keywords.map((k) => ({
      id: k.id,
      theme: k.theme,
      dMean: k.dMean,
      works: k.works,
      r: round(radius(k.works, maxWorks, spec.rMax, spec.rMin)),
      rY: round(radius(k.perYear, maxPerYear, spec.rMax, spec.rMin)),
      text: { en: k.en, zh: k.zh ?? k.en },
    }));
    const L = layoutBeeswarm({ themes: view.themes, keywords, maxD, spec, calloutRank });
    if (L.stats.maxXShift > 0) throw new Error(`${lens}/${name}: a bubble left its x position (${L.stats.maxXShift})`);
    const labelled = { en: 0, zh: 0 };
    const nodes = {};
    for (const k of keywords) {
      const p = L.positions.get(k.id);
      for (const lang of ["en", "zh"]) if (p.label[lang]) labelled[lang]++;
      nodes[k.id] = { x: p.x, y: p.y, r: k.r, rY: k.rY, label: p.label, ...(p.badge ? { badge: p.badge } : {}) };
    }
    out[lens][name] = { ...spec, maxD, guides: L.guides, rows: L.rows, nodes };
    const height = L.rows.reduce((s, r) => s + r.height, 0);
    console.log(
      `${lens.padEnd(4)} ${name.padEnd(6)} ${keywords.length} keywords · labelled at rest EN ${labelled.en}, ZH ${labelled.zh} · rows ${round(height)} units tall · x exact`
    );
  }
}

if (DRY_RUN) {
  console.log("Dry run — nothing written.");
} else {
  writeFileSync(OUT_PATH, JSON.stringify(out, null, 1) + "\n");
  console.log(`Wrote ${OUT_PATH}`);
}
